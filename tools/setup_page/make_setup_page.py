#!/usr/bin/env python3
"""Generate include/SetupPortalPage.h from tools/setup_page/setup_page.html.

The page is minified lightly (leading white space and line breaks) and gzip compressed, so it
takes as little flash as possible. The clock sends it with "Content-Encoding: gzip" and the
browser decompresses it. Run this script again after editing setup_page.html:

    python tools/setup_page/make_setup_page.py
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "setup_page.html")
DST = os.path.join(HERE, "..", "..", "include", "SetupPortalPage.h")

with open(SRC, encoding="utf-8") as f:
    html = "".join(line.strip() for line in f)  # one line, no indentation

raw = html.encode("utf-8")
packed = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: same input -> same output

rows = []
for i in range(0, len(packed), 16):
    rows.append("  " + ",".join("0x%02x" % b for b in packed[i:i + 16]) + ",")

with open(DST, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/setup_page/make_setup_page.py from tools/setup_page/setup_page.html - do not edit.\n")
    f.write("// Page size: %d bytes, gzip compressed: %d bytes.\n" % (len(raw), len(packed)))
    f.write("#pragma once\n#include <Arduino.h>\n\n")
    f.write("static const uint8_t SETUP_PAGE_GZ[] PROGMEM = {\n%s\n};\n" % "\n".join(rows))
    f.write("static const size_t SETUP_PAGE_GZ_LEN = sizeof(SETUP_PAGE_GZ);\n")

print("setup page: %d bytes, gzip: %d bytes -> %s" % (len(raw), len(packed), os.path.normpath(DST)))
